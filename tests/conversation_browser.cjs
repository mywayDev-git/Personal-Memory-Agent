// Disposable rendered UI regression. No running app or personal database is accessed.
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const {readFileSync,mkdirSync,writeFileSync}=require('node:fs');
const {resolve}=require('node:path');
(async()=>{
 const out=resolve(process.env.PMA_TEST_OUTPUT||'.local/conversation-ui');mkdirSync(out,{recursive:true});
 const browser=await chromium.launch({headless:true,channel:'chrome'});
 const checks=[],errors=[];
 const check=(value,label)=>{assert.ok(value,label);checks.push(label);};
 let page;
 try{
  page=await browser.newPage({viewport:{width:1440,height:1000}});
  page.on('pageerror',e=>errors.push(e.message));
  await page.route('http://127.0.0.1:8880/**',async route=>{
   const path=new URL(route.request().url()).pathname;
   let file;
   if(path==='/')file='pma/static/index.html';
   else if(path==='/fixture.js')file='evaluation/chat_ui_fixture.js';
   else if(/^\/static\/[a-z-]+\.(js|css)$/.test(path))file='pma'+path;
   else return route.fulfill({status:404,body:''});
   let body=readFileSync(resolve(file),'utf8');if(path==='/')body=body.replace('/static/app.js','/fixture.js');
   return route.fulfill({body,contentType:path.endsWith('.css')?'text/css':path==='/'?'text/html':'text/javascript'});
  });
  await page.goto('http://127.0.0.1:8880/');
  const input=page.getByLabel('메시지',{exact:true});
  await input.waitFor();check(await input.isVisible(),'빈 화면에서 바로 입력');
  check(await page.locator('#chat-mode').inputValue()==='auto','기본 자동 모드');
  check(await page.locator('.site-header #chat-sidebar').count()===1,'앱 사이드바에 대화 목록 통합');
  await page.getByRole('button',{name:'학습 재개',exact:true}).click();
  await page.getByRole('button',{name:'이어서 진행',exact:true}).waitFor();
  check(await page.locator('.chat-dynamic-actions button').count()===3,'상황별 액션 3개');
  const box=await input.boundingBox();check(box.y+box.height<1000,'입력창 화면 하단 유지');
  const font=await page.locator('.chat-ai').first().evaluate(el=>getComputedStyle(el).fontSize);check(font==='16px','대화 본문 16px, 실제 '+font);
  await page.screenshot({path:resolve(out,'desktop.png')});
  await page.getByRole('button',{name:'진행 이력',exact:true}).click();
  await page.getByRole('dialog').waitFor();
  check((await page.getByRole('dialog').innerText()).includes('사건 시각: 기록에서 확인되지 않음'),'저장일을 사건일로 표시하지 않음');
  check(await page.getByRole('dialog').getAttribute('open')!==null,'이력 패널');
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  check(await page.getByRole('button',{name:'진행 이력 · 선택 완료',exact:true}).isDisabled(),'완료 액션 중복 클릭 차단');
  await page.getByRole('button',{name:'근거 비교',exact:true}).click();
  await page.getByRole('dialog').waitFor();check((await page.getByRole('dialog').innerText()).includes('같은 대상'),'조건 비교 안내');
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  await page.getByRole('button',{name:'부분 근거',exact:true}).click();
  check(await page.locator('.chat-search-info').getAttribute('open')===null,'검색 상세 기본 접힘');
  await page.locator('.chat-evidence>summary').click();
  await page.getByRole('dialog').waitFor();check(await page.getByRole('dialog').locator('.chat-evidence-card').count()===2,'사용된 원문 두 개');
  await page.getByRole('dialog').locator('.chat-citation>summary').first().click();
  check(await page.getByRole('dialog').locator('.chat-source').first().isVisible(),'원문과 인용 강조');
  await page.getByRole('button',{name:'닫기',exact:true}).click();
  await input.fill('첫 번째 초안');await page.getByRole('button',{name:'충돌 기록',exact:true}).click();
  check(await input.inputValue()!=='첫 번째 초안','대화별 초안 격리');
  check(await page.locator('.chat-conflict').isVisible(),'충돌 상태 표현');
  await page.getByRole('button',{name:'부분 근거',exact:true}).click();check(await input.inputValue()==='첫 번째 초안','초안 복구');
  await page.setViewportSize({width:390,height:844});
  await page.locator('#app-menu-toggle').click();
  await page.getByRole('button',{name:'학습 재개',exact:true}).click();
  check(await page.locator('.shell').evaluate(el=>el.classList.contains('sidebar-collapsed')),'모바일 대화 선택 후 목록 접기');
  check(await input.isVisible(),'모바일 입력창 표시');
  check(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'UXR-20 모바일 가로 넘침 없음');
  await page.screenshot({path:resolve(out,'mobile.png')});
  await page.locator('#app-menu-toggle').click();check(await page.locator('#sidebar-scrim').isVisible(),'모바일 서랍 열기');
  await page.keyboard.press('Escape');check(!await page.locator('#sidebar-scrim').isVisible(),'Escape로 서랍 닫기');
  await input.fill('조합 중 Enter');await input.dispatchEvent('keydown',{key:'Enter',isComposing:true,keyCode:229});
  check(await input.inputValue()==='조합 중 Enter','한국어 조합 중 전송 방지');
  await input.press('Shift+Enter');check((await input.inputValue()).includes('\n'),'Shift Enter 줄바꿈');
  await page.locator('.chat-evidence>summary').click();await page.getByRole('dialog').waitFor();
  const panel=await page.getByRole('dialog').boundingBox();check(Math.round(panel.width)===390,'모바일 전체 화면 근거');
  await page.keyboard.press('Escape');check(!await page.getByRole('dialog').count(),'Escape로 근거 닫기');
  await page.setViewportSize({width:390,height:422});
  const zoomBox=await input.boundingBox();
  check(zoomBox.y+zoomBox.height<=422,'200% 확대에 해당하는 축소 뷰포트에서 입력창 접근');
  await page.screenshot({path:resolve(out,'zoom.png')});
  await page.setViewportSize({width:1000,height:850});
  await page.locator('#record-upload').setInputFiles({name:'study.md',mimeType:'text/markdown',buffer:Buffer.from('😀 합성 학습 기록\n'.repeat(500),'utf8')});
  await page.getByRole('dialog').waitFor();
  check((await page.getByRole('dialog').innerText()).includes('아직 개인 기록으로 저장되지 않았습니다'),'업로드 미리보기 선행');
  check(!await page.evaluate(()=>globalThis.fixtureImportCommits),'미승인 파일 저장 방지');
  await page.getByRole('button',{name:'확인하고 저장',exact:true}).click();
  await page.getByRole('dialog').waitFor({state:'hidden'});
  check(await page.evaluate(()=>globalThis.fixtureImportCommits)===1,'업로드 승인 후 한 번 저장');
  await page.locator('#record-upload').setInputFiles({name:'bad.txt',mimeType:'text/plain',buffer:Buffer.from([255])});
  check(!await page.getByRole('dialog').count(),'잘못된 UTF-8 업로드 차단');
  check(!errors.length,'브라우저 실행 오류 없음: '+errors.join(';'));
  writeFileSync(resolve(out,'results.json'),JSON.stringify({passed:checks.length,checks,errors},null,2));
  console.log(JSON.stringify({passed:checks.length,checks}));
 }catch(e){if(page)await page.screenshot({path:resolve(out,'failure.png')});writeFileSync(resolve(out,'failure.txt'),e.stack+'\n'+errors.join('\n')+'\n'+(page?await page.locator('#notice').innerText():''));throw e;}
 finally{await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
