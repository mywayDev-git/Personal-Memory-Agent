// Run against evaluation.chat_ui_server using the documented CUA browser surface.
export async function runChatUI(tab) {
 const p=tab.playwright, checks=[];
 const check=(ok,label)=>{if(!ok)throw Error(label);checks.push(label);};
 const button=name=>p.getByRole('button',{name,exact:true});
 const open=async name=>{await button(name).click();await p.getByRole('heading',{name,exact:true}).waitFor({state:'visible'});await tab.getAXState({emit:false});};
 await open('부분 근거');
 check((await p.locator('#chat-messages').innerText()).includes('기록에서 확인되지 않음'),'partial coverage');
 check(await p.locator('.chat-evidence').getAttribute('open')===null,'evidence collapsed');
 await p.locator('.chat-evidence > summary').click();await tab.getAXState({emit:false});
 await p.getByRole('dialog').waitFor({state:'visible'});
 check(await p.locator('.chat-evidence-panel .chat-evidence-card').count()===2,'two sources');
 await p.locator('.chat-evidence-panel .chat-citation > summary').first().click();await tab.getAXState({emit:false});
 check(await p.locator('.chat-evidence-panel .chat-source').first().isVisible(),'full source');
 await button('닫기').click();await tab.getAXState({emit:false});
 await p.getByLabel('메시지',{exact:true}).fill('첫 번째 초안');
 await open('충돌 기록');
 check((await p.getByLabel('메시지',{exact:true}).evaluate(el=>el.value))!=='첫 번째 초안','draft isolation');
 check(await p.locator('.chat-conflict').isVisible(),'conflict warning');
 await p.getByLabel('메시지',{exact:true}).fill('두 번째 초안');
 await open('부분 근거');
 check((await p.getByLabel('메시지',{exact:true}).evaluate(el=>el.value))==='첫 번째 초안','draft restored');
 await open('동일 사건');
 check((await p.locator('.chat-evidence > summary').innerText())==='근거 2건','same event sources');
 check(await p.locator('.chat-evidence').count()===1,'one evidence group per answer');
 await open('여러 사건');
 check(await p.locator('.chat-block-timeline').count()===2,'separate events');
 check((await p.locator('.chat-event-date').allTextContents()).join(',')==='2025-05-15,2025-07-08','event dates');
 await open('확인 질문');
 check(await p.locator('.chat-choice').count()===2,'clarification choices');
 await p.locator('.chat-choice button').first().click();await tab.getAXState({emit:false});
 await p.locator('.chat-block p').filter({hasText:'후속 답변입니다.'}).last().waitFor({state:'visible'});
 check(await p.locator('.chat-user').count()===2,'clarification follow up');
 await open('진행 중인 대화');
 await p.getByText('자동으로 완료된 답변입니다.',{exact:true}).waitFor({state:'visible',timeoutMs:10000});
 check(await button('보내기').isEnabled(),'resumed request completed');
 await open('긴 대화');
 await p.locator('#chat-messages').press('Control+Home');await tab.getAXState({emit:false});
 const before=await p.locator('#chat-messages').evaluate(el=>el.scrollTop);
 await button('새로고침').click();await tab.getAXState({emit:false});
 const after=await p.locator('#chat-messages').evaluate(el=>el.scrollTop);
 check(Math.abs(before-after)<3,'scroll preserved');
 await p.getByLabel('메시지',{exact:true}).fill('새 답변 이동');await button('보내기').click();await tab.getAXState({emit:false});
 await p.locator('#chat-messages').press('Control+Home');await tab.getAXState({emit:false});
 await button('새 답변 보기 ↓').waitFor({state:'visible'});
 check(true,'new answer indicator while reading history');
 await button('새 답변 보기 ↓').click();await tab.getAXState({emit:false});
 check(!await button('새 답변 보기 ↓').isVisible(),'jump to latest');
 await p.getByLabel('메시지',{exact:true}).fill('실패');await button('보내기').click();await tab.getAXState({emit:false});
 await button('다시 시도').waitFor({state:'visible',timeoutMs:10000});
 check((await p.getByLabel('메시지',{exact:true}).evaluate(el=>el.value))==='실패','failed draft preserved');
 await button('다시 시도').click();await tab.getAXState({emit:false});
 await button('다시 시도').waitFor({state:'hidden'});
 await p.locator('.chat-block p').filter({hasText:'후속 답변입니다.'}).last().waitFor({state:'visible'});
 check(await button('다시 시도').count()===0,'retry succeeded');
 await p.getByLabel('메시지',{exact:true}).fill('중단 테스트');await button('보내기').click();await tab.getAXState({emit:false});
 await button('중단').click();await tab.getAXState({emit:false});
 await p.getByText('중단한 요청입니다. 검증되지 않은 답변은 보관하지 않습니다.',{exact:true}).waitFor({state:'visible'});
 check(true,'cancelled');
 await open('부분 근거');await tab.reload();await tab.getAXState({emit:false});await open('부분 근거');
 check((await p.getByLabel('메시지',{exact:true}).evaluate(el=>el.value))==='첫 번째 초안','draft survives reload');
 const rect=await p.locator('#chat-question').evaluate(el=>({bottom:el.getBoundingClientRect().bottom,viewport:window.innerHeight}));
 check(rect.bottom<rect.viewport,'composer visible');
 return {passed:checks.length,checks};
}
