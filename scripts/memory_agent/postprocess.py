
"""Postprocessing utilities for extracted memories."""

from typing import Any


SCHEMA_VERSION = "4.0"


def build_final_result(
    llm_output: dict[str, Any],
    source_context: dict[str, Any],
) -> dict[str, Any]:
    """Add deterministic metadata and IDs without changing memory semantics."""
    memories = llm_output.get("memories")

    if not isinstance(memories, list):
        raise ValueError("'memories' must be an array")

    final_memories: list[dict[str, Any]] = []

    for index, memory in enumerate(memories, start=1):
        if not isinstance(memory, dict):
            raise ValueError(
                f"memories[{index - 1}] must be an object"
            )

        item = dict(memory)

        # IDs are assigned by Python, not generated by the LLM.
        item.pop("local_id", None)
        item["local_id"] = f"m{index}"

        final_memories.append(item)

    return {
        "schema_version": SCHEMA_VERSION,
        "source_context": dict(source_context),
        "memories": final_memories,
    }


def normalize_reference_time(
    reference_time: Any,
) -> str | None:
    """Normalize a reference-time value without inventing information."""
    if reference_time is None:
        return None

    if not isinstance(reference_time, str):
        raise ValueError("reference_time must be a string or None")

    normalized = reference_time.strip()
    return normalized or None


def make_source_context(
    source_id: str,
    reference_time: Any = None,
    language: str = "ko",
) -> dict[str, Any]:
    """Build the source metadata attached to the final result."""
    if not isinstance(source_id, str) or not source_id.strip():
        raise ValueError("source_id must be a non-empty string")

    if not isinstance(language, str) or not language.strip():
        raise ValueError("language must be a non-empty string")

    return {
        "source_id": source_id.strip(),
        "reference_time": normalize_reference_time(reference_time),
        "language": language.strip(),
    }
